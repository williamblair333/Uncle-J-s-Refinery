#!/usr/bin/env python3
"""tools.py - catalog, lint and wire up every project's ready-made tools

A tool is a `just` recipe in the `tools` group (a `[group('tools')]` line under
its doc comment) whose body runs one script. The rules a tool meets are in
docs/TOOLS-STANDARD.md.

  just tools list [TERM] [--tools] [--json] every project's recipes (* = tool) under PROJ_ROOT
  just tools lint [REPO] [--all] [--json]   check REPO's tools against the standard
  just tools lint --script FILE             check one script (before it has a recipe)
  just tools sync [--check] [--dry-run]     write the global justfile, so any session
                                            can run `just -g <project> <recipe>`

PROJ_ROOT (default /opt/proj) is where projects live. GLOBAL_JUSTFILE overrides
where `sync` writes (default $XDG_CONFIG_HOME/just/justfile, else
~/.config/just/justfile).

Exit codes: 0 ok, 1 lint errors / sync --check stale, 2 usage or environment error.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

VERSION = "1.0.0"
REPO_ROOT = Path(__file__).resolve().parents[1]
JUSTFILE_NAMES = ("justfile", "Justfile", ".justfile")
MARKER = "# GENERATED by tools.py sync"
MODULE_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_-]*$")
RESERVED = {"default", "tools"}
SUBCOMMANDS = {"list", "lint", "sync"}

HEADER = re.compile(r"""^\s*(#|\"\"\"|''')?\s*[\w./-]+\s+[-—–]\s+\S""")
HOME_PATH = re.compile(r"(/home/[a-z_][a-z0-9_-]*|/Users/[A-Za-z])")
UID_1000 = re.compile(r"\b1000\b")
TOOLS_GROUP = re.compile(r"""^\s*\[\s*group\s*\(\s*['"]tools['"]\s*\)""", re.M)


class ToolsError(Exception):
    pass


# ------------------------------------------------------------- discovery ----

def proj_root() -> Path:
    return Path(os.environ.get("PROJ_ROOT", "/opt/proj")).expanduser()


def find_justfile(directory: Path) -> Path | None:
    for name in JUSTFILE_NAMES:
        candidate = directory / name
        if candidate.is_file():
            return candidate
    return None


def dump(justfile: Path) -> dict | None:
    """The justfile as just's own JSON, or None when just can't parse it."""
    if shutil.which("just") is None:
        raise ToolsError("`just` is not installed")
    try:
        out = subprocess.run(
            ["just", "--justfile", str(justfile), "--dump", "--dump-format", "json"],
            capture_output=True, text=True, timeout=20, check=False,
        )
    except subprocess.TimeoutExpired:
        return None
    if out.returncode != 0:
        return None
    try:
        return json.loads(out.stdout)
    except json.JSONDecodeError:
        return None


def iter_recipes(data: dict, prefix: str = ""):
    """(namepath, recipe) for every public recipe, modules included."""
    for name, recipe in sorted(data.get("recipes", {}).items()):
        if recipe.get("private") or name.startswith("_"):
            continue
        yield prefix + name, recipe
    for mod_name, module in sorted((data.get("modules") or {}).items()):
        yield from iter_recipes(module, f"{prefix}{mod_name} ")


def _runs_command(value) -> bool:
    """True if an assignment's parsed value contains a backtick or shell() call."""
    if isinstance(value, list):
        if value and value[0] == "evaluate":
            return True
        if len(value) > 1 and value[0] == "call" and value[1] == "shell":
            return True
        return any(_runs_command(v) for v in value)
    return False


def runs_at_load(data: dict) -> bool:
    """Would loading this justfile run a command? Then every `just -g` call would run it.

    Read from just's own parse (backticks dump as ["evaluate", ...]), modules included,
    so multi-line assignments count and backticks in comments don't.
    """
    if any(_runs_command(a.get("value")) for a in (data.get("assignments") or {}).values()):
        return True
    return any(runs_at_load(m) for m in (data.get("modules") or {}).values())


def is_tool(recipe: dict) -> bool:
    return {"group": "tools"} in (recipe.get("attributes") or [])


def body_text(recipe: dict) -> str:
    """Recipe body with every {{interpolation}} replaced by a NUL marker."""
    return "\n".join(
        "".join(f if isinstance(f, str) else "\0" for f in line)
        for line in recipe.get("body") or []
    )


def _interpolated_paths(node) -> list[str]:
    """Paths built inside {{...}}: quote(source_directory() / "scripts/x.py") dumps as
    ["call", "quote", ["join", ["call", "source_directory"], "scripts/x.py"]]."""
    if not isinstance(node, list):
        return []
    if node and node[0] == "join":
        return [p for p in node[1:] if isinstance(p, str)] + [x for p in node[1:] for x in _interpolated_paths(p)]
    return [x for child in node for x in _interpolated_paths(child)]


def script_of(recipe: dict, repo: Path) -> Path | None:
    """The script a recipe runs: first .py/.sh in its body, else an executable."""
    tokens = [p for line in recipe.get("body") or [] for f in line
              if not isinstance(f, str) for p in _interpolated_paths(f)]
    for raw in re.split(r"[\s\"']+", body_text(recipe)):
        token = raw.replace("\0", "")
        if raw.startswith("\0"):  # "{{justfile_directory()}}/scripts/x.py"
            token = token.lstrip("/")
        if not token or ".venv/" in token or token.startswith("-"):
            continue
        tokens.append(token)
    base = repo.resolve()
    found = [(repo / t).resolve() for t in tokens if (repo / t).is_file()]
    found = [p for p in found if p.is_relative_to(base) and ".venv" not in p.relative_to(base).parts]
    for path in found:
        if path.suffix in (".py", ".sh"):
            return path
    for path in found:
        if os.access(path, os.X_OK):
            return path
    return None


# ------------------------------------------------------------------ lint ----

def _test_exists(script: Path, repo: Path, src: str) -> bool:
    if _has_flag(src, "--test"):
        return True
    stem = script.stem.replace("-", "_")
    tests = repo / "tests"
    if not tests.is_dir():
        return False
    patterns = (f"test_{stem}*.py", f"test_{stem}*.sh", f"*{script.stem}*.bats", f"*{stem}*.bats")
    return any(next(tests.rglob(p), None) for p in patterns)


def _code(src: str) -> str:
    """Source without comment lines: a flag named only in a comment doesn't count."""
    return "\n".join(line for line in src.splitlines() if not line.lstrip().startswith("#"))


def _has_flag(code: str, flag: str) -> bool:
    return re.search(re.escape(flag) + r"(?![\w-])", code) is not None


def lint_script(script: Path, repo: Path) -> list[dict]:
    """Problems with one tool script. Level E fails the lint, W only reports."""
    try:
        src = script.read_text(encoding="utf-8", errors="replace")
    except OSError as exc:
        return [{"level": "E", "code": "unreadable", "msg": str(exc)}]
    problems: list[dict] = []

    def add(level: str, code: str, msg: str) -> None:
        problems.append({"level": level, "code": code, "msg": msg})

    lines = src.splitlines()
    code = _code(src)
    head = "\n".join(lines[:20])
    read_only = "read-only" in head.lower()
    if not any(HEADER.match(line) for line in lines[:20]):
        add("E", "header", "no '<name> - <what it does>' line in the first 20 lines")
    if not _has_flag(code, "--help") and "argparse" not in code:
        add("E", "help", "no --help")
    if not _has_flag(code, "--version"):
        add("E", "version", "no --version")
    if not read_only:
        if not _has_flag(code, "--dry-run"):
            add("E", "dry-run", "no --dry-run (or say 'read-only' in the header if it changes nothing)")
        if not _has_flag(code, "--check") and not _has_flag(code, "--status"):
            add("E", "check", "no read-only --check or --status mode")
    if not _has_flag(code, "--json"):
        add("W", "json", "no --json output for agents")
    if not _test_exists(script, repo, code):
        add("E", "test", f"no tests/test_{script.stem.replace('-', '_')}.* and no --test mode")

    for number, line in enumerate(lines, 1):
        if line.lstrip().startswith("#"):
            continue
        if HOME_PATH.search(line):
            add("E", "home-path", f"line {number}: hard-coded home folder; use $HOME or Path.home()")
        if UID_1000.search(line) and ("id -u" in line or "uid" in line.lower()):
            add("W", "uid", f"line {number}: assumes user ID 1000")
        if "/opt/proj" in line and "PROJ_ROOT" not in line:
            add("W", "proj-root", f"line {number}: hard-coded /opt/proj; use ${{PROJ_ROOT:-/opt/proj}}")
    return problems


def _relative(script: Path | None, repo: Path) -> str | None:
    if script is None:
        return None
    try:
        return str(script.relative_to(repo.resolve()))
    except ValueError:
        return str(script)


def repo_of(path: Path) -> Path:
    """The nearest folder above path holding a justfile or .git (else path's folder)."""
    for parent in path.parents:
        if find_justfile(parent) or (parent / ".git").exists():
            return parent
    return path.parent


def lint_repo(repo: Path, all_recipes: bool = False) -> list[dict]:
    """One row per checked recipe. Raises ToolsError when the repo can't be read."""
    justfile = find_justfile(repo)
    if justfile is None:
        raise ToolsError(f"no justfile in {repo}")
    data = dump(justfile)
    if data is None:
        raise ToolsError(f"just can't parse {justfile}")
    rows = []
    for name, recipe in iter_recipes(data):
        tool = is_tool(recipe)
        if not tool and not all_recipes:
            continue
        script = script_of(recipe, repo)
        if script is None and not tool:
            continue
        problems = []
        if "justfile_directory" in json.dumps(recipe.get("body") or []):
            problems.append({"level": "E", "code": "justfile-dir",
                             "msg": "justfile_directory() points at the global justfile under `just -g`; use source_directory()"})
        if not recipe.get("doc"):
            problems.append({"level": "E", "code": "doc", "msg": "recipe has no doc comment"})
        if script is None:
            problems.append({"level": "E", "code": "script", "msg": "body runs no script in this repo"})
        else:
            problems += lint_script(script, repo)
        rows.append({"recipe": name, "tool": tool, "script": _relative(script, repo), "problems": problems})
    # A file that declares tools but parses to none means just's dump format moved
    # under us; a silent "0 tools, 0 failing" would read as green forever.
    if not any(r["tool"] for r in rows) and TOOLS_GROUP.search(justfile.read_text(errors="replace")):
        raise ToolsError(f"{justfile} declares group('tools') but none were parsed; has `just --dump` changed format?")
    return rows


# ---------------------------------------------------------- list / sync ----

def projects(root: Path):
    """(name, dir, justfile) for each project folder holding a justfile."""
    if not root.is_dir():
        return
    for directory in sorted(p for p in root.iterdir() if p.is_dir()):
        if directory.name.startswith((".", "_")):
            continue
        justfile = find_justfile(directory)
        if justfile:
            yield directory.name, directory, justfile


def catalog(root: Path, all_recipes: bool = False, term: str = "") -> tuple[list[dict], list[str]]:
    rows, broken = [], []
    needle = term.lower()
    for name, _directory, justfile in projects(root):
        data = dump(justfile)
        if data is None:
            broken.append(name)
            continue
        for recipe_name, recipe in iter_recipes(data):
            if recipe_name == "default" or (not all_recipes and not is_tool(recipe)):
                continue
            doc = recipe.get("doc") or ""
            if not doc and not is_tool(recipe):
                continue  # undocumented recipes aren't on the menu
            if needle and needle not in f"{name} {recipe_name} {doc}".lower():
                continue
            rows.append({"project": name, "recipe": recipe_name, "doc": doc, "tool": is_tool(recipe)})
    return rows, broken


def global_justfile_path() -> Path:
    override = os.environ.get("GLOBAL_JUSTFILE")
    if override:
        return Path(override).expanduser()
    config = Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config")
    return config / "just" / "justfile"


def render_global(root: Path) -> tuple[str, list[str]]:
    """The global justfile's text, and the projects left out with why."""
    tools_py = json.dumps(str(REPO_ROOT / "scripts" / "tools.py"))
    lines = [
        f"{MARKER} from {REPO_ROOT}/scripts/tools.py; do not edit, rerun `just tools sync`.",
        "# Run any project's recipe from any folder: just -g <project> <recipe>",
        "",
        "# every project and its recipes",
        "default:",
        "    @just --justfile {{quote(justfile())}} --list --list-submodules",
        "",
        "# find a ready-made recipe in any project: just -g tools [TERM] [--tools] | lint [REPO] | sync",
        "[positional-arguments]",
        "tools *args:",
        f"    @cd {{{{quote(invocation_directory())}}}} && python3 {tools_py} \"$@\"",
        "",
    ]
    skipped = []
    for name, _directory, justfile in projects(root):
        if not MODULE_NAME.match(name) or name in RESERVED:
            skipped.append(f"{name} (not usable as a module name)")
            continue
        data = dump(justfile)
        if data is None:
            skipped.append(f"{name} (just can't parse its justfile)")
            continue
        if runs_at_load(data):
            skipped.append(f"{name} (runs a command when loaded: backtick or shell() assignment)")
            continue
        lines.append(f"mod {name} {json.dumps(str(justfile))}")
    return "\n".join(lines) + "\n", skipped


def write_atomic(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=path.parent, delete=False) as tmp:
        tmp.write(content)
        temp_name = tmp.name
    os.replace(temp_name, path)


def rejection(content: str) -> str | None:
    """None when just accepts the generated file, else its error."""
    if shutil.which("just") is None:
        raise ToolsError("`just` is not installed")
    with tempfile.TemporaryDirectory() as tmp:
        candidate = Path(tmp) / "justfile"
        candidate.write_text(content)
        out = subprocess.run(["just", "--justfile", str(candidate), "--summary"],
                             capture_output=True, text=True, timeout=60, check=False)
    return None if out.returncode == 0 else (out.stderr.strip() or "just rejected it")


# ------------------------------------------------------------------- cli ----

def print_lint(rows: list[dict]) -> None:
    for row in rows:
        errors = [p for p in row["problems"] if p["level"] == "E"]
        mark = "FAIL" if errors else ("WARN" if row["problems"] else " OK ")
        kind = "tool" if row["tool"] else "    "
        print(f"[{mark}] {kind} {row['recipe']:<22} {row['script'] or '-'}")
        for p in row["problems"]:
            print(f"         {p['level']} {p['code']:<10} {p['msg']}")


def cmd_list(args, root: Path) -> int:
    rows, broken = catalog(root, not args.tools, args.term)
    if args.json:
        print(json.dumps({"tools": rows, "broken_justfiles": broken}, separators=(",", ":")))
        return 0
    width = max((len(r["project"]) + len(r["recipe"]) for r in rows), default=10) + 1
    for r in rows:
        mark = "*" if r["tool"] else " "
        print(f"{mark} {(r['project'] + ' ' + r['recipe']):<{width}}  {r['doc']}")
    kind = "tools" if args.tools else "recipes (* = tool)"
    count = len({r["project"] for r in rows})
    print(f"\n{len(rows)} {kind} in {count} projects under {root}. Run one: just -g <project> <recipe>")
    if broken:
        print(f"skipped (just can't parse): {', '.join(broken)}", file=sys.stderr)
    return 0


def cmd_lint(args) -> int:
    repo = Path(args.repo).resolve()
    if args.script:
        script = Path(args.script).resolve()
        if args.repo == ".":
            repo = repo_of(script)
        rows = [{"recipe": "-", "tool": True, "script": str(script), "problems": lint_script(script, repo)}]
    else:
        rows = lint_repo(repo, args.all)
    failed = [r for r in rows if r["tool"] and any(p["level"] == "E" for p in r["problems"])]
    if args.json:
        print(json.dumps({"recipes": rows, "failed_tools": len(failed)}, separators=(",", ":")))
    else:
        print_lint(rows)
        tools = sum(1 for r in rows if r["tool"])
        hint = "" if args.all else "  (--all also reports recipes outside the tools group)"
        print(f"\n{tools} tools checked, {len(failed)} failing{hint}")
    return 1 if failed else 0


def cmd_sync(args, root: Path) -> int:
    target = global_justfile_path()
    content, skipped = render_global(root)
    current = target.read_text() if target.is_file() else None
    status = "current" if current == content else ("missing" if current is None else "stale")
    report = {"path": str(target), "status": status, "skipped": skipped}
    if args.check:
        print(json.dumps(report, separators=(",", ":")) if args.json else f"{target}: {status}")
        return 0 if status == "current" else 1
    if args.dry_run:
        if args.json:
            print(json.dumps(report | {"content": content}, separators=(",", ":")))
        else:
            print(content, end="")
            for s in skipped:
                print(f"# skipped: {s}", file=sys.stderr)
        return 0
    if current is not None and MARKER not in current and not args.force:
        print(f"tools.py sync: {target} wasn't written by this script; --force replaces it", file=sys.stderr)
        return 2
    error = rejection(content)
    if error:
        print(f"tools.py sync: just rejects the generated file, nothing written:\n{error}", file=sys.stderr)
        return 1
    if status != "current":
        write_atomic(target, content)
    else:
        os.utime(target)  # newer than every justfile now, so the session-start hook stops re-checking
    report["status"] = "current" if status == "current" else "written"
    report["projects"] = content.count("\nmod ")
    if args.json:
        print(json.dumps(report, separators=(",", ":")))
    else:
        print(f"{target}: {report['status']} ({report['projects']} projects)")
        for s in skipped:
            print(f"  skipped {s}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="tools.py", description=__doc__.split("\n\n")[0])
    parser.add_argument("--version", action="version", version=f"tools.py {VERSION}")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_list = sub.add_parser("list", help="every project's recipes; * marks tools that meet the standard")
    p_list.add_argument("term", nargs="?", default="")
    p_list.add_argument("--tools", action="store_true", help="only recipes in the tools group")
    p_list.add_argument("--json", action="store_true")

    p_lint = sub.add_parser("lint", help="check a repo's tools against docs/TOOLS-STANDARD.md")
    p_lint.add_argument("repo", nargs="?", default=".")
    p_lint.add_argument("--all", action="store_true", help="also report recipes outside the tools group")
    p_lint.add_argument("--script", help="lint one script file instead of a repo's recipes")
    p_lint.add_argument("--json", action="store_true")

    p_sync = sub.add_parser("sync", help="write the global justfile")
    p_sync.add_argument("--check", action="store_true", help="exit 1 if the global justfile is missing or stale")
    p_sync.add_argument("--dry-run", action="store_true", help="print what would be written")
    p_sync.add_argument("--force", action="store_true", help="replace a global justfile this script didn't write")
    p_sync.add_argument("--json", action="store_true")

    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or (argv[0] not in SUBCOMMANDS and argv[0] not in ("-h", "--help", "--version")):
        argv.insert(0, "list")   # `just -g tools backup` searches the catalog
    args = parser.parse_args(argv)
    root = proj_root()
    try:
        if args.cmd == "list":
            return cmd_list(args, root)
        if args.cmd == "lint":
            return cmd_lint(args)
        return cmd_sync(args, root)
    except ToolsError as exc:
        print(f"tools.py {args.cmd}: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
